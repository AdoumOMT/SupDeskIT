target_size = min(len(haute_priorite), len(moyenne_priorite), len(basse_priorite))

data = pd.DataFrame({
    'description': haute_priorite[:target_size] + moyenne_priorite[:target_size] + basse_priorite[:target_size],
    'priorite': ['haute'] * target_size + ['moyenne'] * target_size + ['basse'] * target_size
})

print(data.describe())

X_train, X_test, y_train, y_test = train_test_split(data['description'], data['priorite'], test_size=0.2, random_state=42)

model = Pipeline([
    ('tfidf', TfidfVectorizer()),
    ('clf', MultinomialNB())
])

model.fit(X_train, y_train)

y_pred = model.predict(X_test)
print("Répartition du dataset :")
print(data['priorite'].value_counts())
print("\nRapport de classification :")
print(classification_report(y_test, y_pred))

model_dir = os.path.dirname(__file__)
joblib.dump(model, os.path.join(model_dir, 'priorite_classifier.pkl'))


report = classification_report(y_test, y_pred, output_dict=True)
print(report)
os.makedirs('../accounts/ml_model', exist_ok=True)

output_path = os.path.join(os.path.dirname(__file__), 'rapport_ml.json')
with open(output_path, 'w') as f:
    json.dump(report, f, indent=4)

print(f"Fichier 'rapport.json' généré avec succès à {output_path}")

